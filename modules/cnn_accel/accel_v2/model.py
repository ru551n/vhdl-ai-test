class Model:
    """A small, explicit dataflow graph plus the deterministic RNG that
    fills in every op's random weights/biases/inputs/per-channel scale
    tables. Two `Model(seed=S)` built by an identical sequence of calls
    are byte-identical; a different `seed` (almost certainly) is not --
    exercised directly by `tests/test_model.py`'s determinism test."""

    def __init__(self, seed: int, name: str = "model", *, shapes_only: bool = False) -> None:
        """`shapes_only` builds a graph for **planning only**: weights,
        biases, scale tables and input data are left empty instead of
        drawn from the RNG.

        It exists for one purpose: reasoning about a network at its real
        size. YOLOv8n's weights are 3.2 million int8 values, and the
        tiling selection rule (`tiling_select.py`) plans a few thousand
        candidate strip sub-programs over them -- drawing and copying
        those lists would dominate the run by orders of magnitude while
        changing nothing, since `planner.py` only ever asks a conv for
        its *shape* (`Conv2dOp.weight_layer_desc`, whose byte counts come
        from the channel and kernel counts alone). A `shapes_only` model
        must never be handed to `reference.py` or `program.py`, which do
        read the values."""
        self.seed = seed
        self.name = name
        self.shapes_only = shapes_only
        self._rng = _Rng(seed)
        self.ops: list[Op] = []
        self.tensors: list[Tensor] = []
        self.inputs: list[Tensor] = []
        self.outputs: list[Tensor] = []
        self._counter = count()

    # -- naming / bookkeeping ---------------------------------------------

    def _auto_name(self, prefix: str) -> str:
        return f"{prefix}{next(self._counter)}"

    def _register_op(self, op: Op) -> None:
        op_index = len(self.ops)
        for t in op.inputs:
            t.consumers.append(op_index)
        self.ops.append(op)
        self.tensors.append(op.output)

    # -- graph inputs/outputs ----------------------------------------------

    def input(
        self, height: int, width: int, channels: int, scale: float = 1.0, name: str | None = None
    ) -> Tensor:
        """A tensor materialized in DDR before the program starts (the
        residency policy's one legitimate "initial input" round trip).
        Its data is generated now, deterministically, from the model's
        RNG."""
        t = Tensor(
            name=name or self._auto_name("input"),
            height=height,
            width=width,
            channels=channels,
            quant=QuantParams(scale),
            is_input=True,
        )
        t.data = [] if self.shapes_only else self._rng.int8_list(height * width * channels)
        self.inputs.append(t)
        self.tensors.append(t)
        return t

    def output(self, tensor: Tensor) -> Tensor:
        """Mark `tensor` a graph output: `planner.py` always lands it in
        the DDR `OUTPUTS` region (never `LOCAL_TENSOR`), matching the
        residency policy's "DDR is backing storage only... for... final
        outputs"."""
        if tensor.is_output:
            return tensor
        if tensor.alias_parent is not None:
            raise ValueError(
                f"cannot mark '{tensor.name}' a graph output: it is aliased into "
                f"'{alias_root(tensor).name}''s buffer (as a "
                f"{tensor.alias_role} at plane offset {alias_plane_offset_total(tensor)}), "
                "and a graph output must own a DDR OUTPUTS allocation of its own. "
                f"Use `model.output(model.copy({tensor.name!r}-tensor))` to materialize "
                "an independent copy first."
            )
        tensor.is_output = True
        self.outputs.append(tensor)
        return tensor

    # -- ops -----------------------------------------------------------------

    def conv2d(
        self,
        x: Tensor,
        out_channels: int,
        *,
        kernel: tuple[int, int] = (3, 3),
        stride: tuple[int, int] = (1, 1),
        padding: tuple[int, int, int, int] = (0, 0, 0, 0),
        pad_value: int = 0,
        bias: bool = True,
        activation: Activation = Activation.RELU,
        clamp: tuple[int, int] | None = None,
        requant_scale: int | None = None,
        requant_shift: int | None = None,
        weight_scale: float = 1.0,
        output_scale: float = 1.0,
        per_channel: bool = False,
        weight_reuse_from: Tensor | None = None,
        name: str | None = None,
    ) -> Tensor:
        """`CONV2D`. `padding` is `(top, bottom, left, right)`.

        `pad_value` is the int8 value padded taps take (ISA v2.1) -- the
        input tensor's quantization zero-point in a real network, not 0.
        `QuantParams` models symmetric quantization and has no zero-point
        field, so it is passed explicitly, exactly as `pool_max`/
        `pool_avg` take it; the default of 0 keeps every existing program
        bit-identical.

        If `requant_scale`/`requant_shift` are both omitted they are
        derived from `x.quant.scale * weight_scale / output_scale` via
        `quantize_scale` -- convenient for a test that only cares about
        shapes, while boundary-rounding tests can still pass exact
        integers.

        `weight_reuse_from` names the OUTPUT tensor of an earlier
        `conv2d` call whose weight/bias/scale-table this op reuses
        verbatim (ISA v2.0 `WEIGHT_REUSE`, R6); geometry
        (`in_channels`/`out_channels`/`kernel`) must match, checked here
        rather than left for `program.py` to discover late."""
        kh, kw = kernel
        sh, sw = stride
        pt, pb, pl, pr = padding
        out_h = (x.height + pt + pb - kh) // sh + 1
        out_w = (x.width + pl + pr - kw) // sw + 1
        if out_h <= 0 or out_w <= 0:
            raise ValueError(f"conv2d: non-positive output dims out_h={out_h} out_w={out_w}")
        if not -128 <= pad_value <= 127:
            raise ValueError(f"conv2d: pad_value must be int8, got {pad_value}")

        if weight_reuse_from is not None:
            reused = weight_reuse_from.producer
            if not isinstance(reused, Conv2dOp):
                raise TypeError("weight_reuse_from must be the output of an earlier conv2d")
            if reused.inputs[0].channels != x.channels or reused.kernel != kernel:
                raise ValueError(
                    "weight_reuse_from geometry mismatch: reused conv has "
                    f"in_channels={reused.inputs[0].channels} kernel={reused.kernel}, "
                    f"this conv wants in_channels={x.channels} kernel={kernel}"
                )
            if reused.output.channels != out_channels:
                raise ValueError(
                    f"weight_reuse_from has out_channels={reused.output.channels}, "
                    f"this conv wants out_channels={out_channels}"
                )
            weight, bias_values, per_channel_scale = reused.weight, reused.bias, reused.per_channel_scale
        elif self.shapes_only:
            reused = None
            weight = []
            bias_values = [0] * out_channels if bias else None
            per_channel_scale = [(1, 0)] * out_channels if per_channel else None
        else:
            reused = None
            weight = self._rng.int8_list(out_channels * kh * kw * x.channels, low=-127, high=127)
            bias_values = self._rng.bias_list(out_channels) if bias else None
            per_channel_scale = self._rng.scale_table(out_channels) if per_channel else None

        if requant_scale is None or requant_shift is None:
            effective_scale = (x.quant.scale * weight_scale) / output_scale
            requant_scale, requant_shift = quantize_scale(effective_scale)

        out_t = Tensor(
            name=name or self._auto_name("conv"),
            height=out_h,
            width=out_w,
            channels=out_channels,
            quant=QuantParams(output_scale),
        )
        op = Conv2dOp(
            name=out_t.name,
            inputs=[x],
            output=out_t,
            weight=weight,
            bias=bias_values,
            kernel=kernel,
            stride=stride,
            padding=padding,
            activation=activation,
            clamp=clamp,
            requant_scale=requant_scale,
            requant_shift=requant_shift,
            per_channel_scale=per_channel_scale,
            pad_value=pad_value,
            weight_reuse=reused is not None,
            reused_weight_op=reused,
        )
        out_t.producer = op
        self._register_op(op)
        return out_t

    def _pool(
        self,
        x: Tensor,
        mode: str,
        kernel: tuple[int, int],
        stride: tuple[int, int],
        padding: tuple[int, int, int, int],
        pad_value: int,
        activation: Activation,
        clamp: tuple[int, int] | None,
        requant_scale: int | None,
        requant_shift: int | None,
        name: str | None,
    ) -> Tensor:
        kh, kw = kernel
        sh, sw = stride
        pt, pb, pl, pr = padding
        out_h = (x.height + pt + pb - kh) // sh + 1
        out_w = (x.width + pl + pr - kw) // sw + 1
        if out_h <= 0 or out_w <= 0:
            raise ValueError(f"{mode} pool: non-positive output dims out_h={out_h} out_w={out_w}")
        if not -128 <= pad_value <= 127:
            raise ValueError(f"{mode} pool: pad_value must be int8, got {pad_value}")

        if mode == "avg":
            if requant_scale is None or requant_shift is None:
                requant_scale, requant_shift = quantize_scale(1.0 / (kh * kw))
        else:
            requant_scale, requant_shift = requant_scale or 0, requant_shift or 0

        out_t = Tensor(
            name=name or self._auto_name(f"pool_{mode}"),
            height=out_h,
            width=out_w,
            channels=x.channels,
            quant=x.quant,
        )
        op = PoolOp(
            name=out_t.name,
            inputs=[x],
            output=out_t,
            mode=mode,
            kernel=kernel,
            stride=stride,
            padding=padding,
            pad_value=pad_value,
            activation=activation,
            clamp=clamp,
            requant_scale=requant_scale,
            requant_shift=requant_shift,
        )
        out_t.producer = op
        self._register_op(op)
        return out_t

    def pool_max(
        self,
        x: Tensor,
        *,
        kernel: tuple[int, int] = (2, 2),
        stride: tuple[int, int] = (2, 2),
        padding: tuple[int, int, int, int] = (0, 0, 0, 0),
        pad_value: int = 0,
        name: str | None = None,
    ) -> Tensor:
        """`OPCODE_POOL_MAX`: no epilogue at all in the golden model
        (`cnn_accel_model.pool_max` bypasses `bias_requantize_relu`), so
        `activation`/`clamp`/`requant` are not exposed here.

        `padding` is `(top, bottom, left, right)` and `pad_value` is the
        int8 value padded taps take -- the input tensor's quantization
        zero-point in a real network, not 0. `QuantParams` has no
        zero-point field of its own (it models symmetric quantization
        only), so this is passed explicitly rather than derived; the
        default of 0 keeps every pre-v2.1 program bit-identical.

        YOLOv8n's SPPF: `kernel=(5, 5), stride=(1, 1), padding=(2, 2, 2,
        2), pad_value=-128`."""
        return self._pool(
            x, "max", kernel, stride, padding, pad_value,
            Activation.NONE, None, None, None, name,
        )

    def pool_avg(
        self,
        x: Tensor,
        *,
        kernel: tuple[int, int] = (2, 2),
        stride: tuple[int, int] = (2, 2),
        padding: tuple[int, int, int, int] = (0, 0, 0, 0),
        pad_value: int = 0,
        activation: Activation = Activation.NONE,
        clamp: tuple[int, int] | None = None,
        requant_scale: int | None = None,
        requant_shift: int | None = None,
        name: str | None = None,
    ) -> Tensor:
        """`OPCODE_POOL_AVG`: divides by the pool area via
        `requant_scale`/`requant_shift`, defaulted to `1/(kh*kw)` unless
        overridden (matching `cnn_accel_model.pool_avg`'s documented
        "division via bias_requant"). `padding`/`pad_value` as for
        `pool_max`; note the padded taps are summed like any other, so a
        padded average is a "count-include-pad" average -- a ratified
        decision (follows from dividing through the fixed-per-descriptor
        `bias_requant` epilogue, which has no per-position divisor),
        deliberately different from TOSA's count-exclude-pad
        `avg_pool2d` (see `doc/cnn_accel_top_v2_arch.md` §5.2a, and
        `cnnc.frontend.tosa_import._INEXACT_OPS["tosa.avg_pool2d"]` for
        why the compiler refuses to lower onto this opcode)."""
        return self._pool(
            x, "avg", kernel, stride, padding, pad_value,
            activation, clamp, requant_scale, requant_shift, name,
        )

    def add(
        self,
        a: Tensor,
        b: Tensor,
        *,
        requant_scale: int | None = None,
        requant_shift: int | None = None,
        output_scale: float | None = None,
        name: str | None = None,
    ) -> Tensor:
        """`OPCODE_ADD`. `a`/`b` must share a shape. See `AddOp`/
        `reference.py` for the single-shared-requant-pair semantics this
        resolves ISA ambiguity #1 with."""
        if (a.height, a.width, a.channels) != (b.height, b.width, b.channels):
            raise ValueError(
                f"add: shape mismatch {a.height,a.width,a.channels} vs {b.height,b.width,b.channels}"
            )
        if requant_scale is None or requant_shift is None:
            eff = a.quant.scale / (output_scale if output_scale is not None else a.quant.scale)
            requant_scale, requant_shift = quantize_scale(eff)
        out_t = Tensor(
            name=name or self._auto_name("add"),
            height=a.height,
            width=a.width,
            channels=a.channels,
            quant=QuantParams(output_scale if output_scale is not None else a.quant.scale),
        )
        op = AddOp(
            name=out_t.name,
            inputs=[a, b],
            output=out_t,
            requant_scale=requant_scale,
            requant_shift=requant_shift,
        )
        out_t.producer = op
        self._register_op(op)
        return out_t

    def upsample2x(self, x: Tensor, *, name: str | None = None) -> Tensor:
        """`OPCODE_UPSAMPLE`, nearest-neighbour 2x2 replicate."""
        out_t = Tensor(
            name=name or self._auto_name("upsample"),
            height=x.height * 2,
            width=x.width * 2,
            channels=x.channels,
            quant=x.quant,
        )
        op = UpsampleOp(name=out_t.name, inputs=[x], output=out_t, factor=2)
        out_t.producer = op
        self._register_op(op)
        return out_t

    def depth_to_space(self, x: Tensor, *, factor: int = 2, name: str | None = None) -> Tensor:
        """`OPCODE_DEPTH_TO_SPACE`: pixel-shuffle `x` by `factor`, turning
        `factor**2 * C` channels into a `factor`-times-larger frame of `C`.

        Unlike `upsample2x` the output channel count is *derived*, not
        copied: `C_out = C_in / factor**2`. Both hardware preconditions are
        checked here (see `DepthToSpaceOp`) so a bad shape fails in the
        test builder, where the message is readable, rather than as an
        `ERR_BAD_GEOMETRY` from the DUT."""
        if factor != 2:
            raise ValueError(f"depth_to_space: v1 hardware implements factor 2 only, got {factor}")
        if x.channels % (factor * factor) != 0:
            raise ValueError(
                f"depth_to_space: in_channels {x.channels} is not a multiple of factor**2 = {factor * factor}"
            )
        out_channels = x.channels // (factor * factor)
        if out_channels % PLANE_CHANNELS != 0:
            raise ValueError(
                f"depth_to_space: out_channels {out_channels} must be a whole number of "
                f"{PLANE_CHANNELS}-channel activation-plane tiles -- the engine moves whole "
                "tiles and cannot gather byte lanes within one. Pad the channel count."
            )
        out_t = Tensor(
            name=name or self._auto_name("depth_to_space"),
            height=x.height * factor,
            width=x.width * factor,
            channels=out_channels,
            quant=x.quant,
        )
        op = DepthToSpaceOp(name=out_t.name, inputs=[x], output=out_t, factor=factor)
        out_t.producer = op
        self._register_op(op)
        return out_t

    def copy(self, x: Tensor, *, name: str | None = None) -> Tensor:
        """`OPCODE_COPY`: local-to-local (or any-space-to-any-space)
        byte copy, shape/quant preserved exactly."""
        out_t = Tensor(
            name=name or self._auto_name("copy"), height=x.height, width=x.width, channels=x.channels, quant=x.quant
        )
        op = CopyOp(name=out_t.name, inputs=[x], output=out_t)
        out_t.producer = op
        self._register_op(op)
        return out_t

    # -- channel concatenation / splitting (no hardware, see below) --------

    def split(self, x: Tensor, sizes: list[int], *, names: list[str] | None = None) -> list[Tensor]:
        """Split `x` along channels into `len(sizes)` tensors -- **free**:
        no opcode, no instruction, no byte moved.

        The section-3 activation layout is channel-plane-major
        (`((c_tile * H + y) * W + x) * T + t`, `T = 8`), so `x` is
        `ceil(C/T)` contiguous planes of `H*W*T` bytes and a channel
        range starting at a multiple of `T` is just a contiguous
        sub-range of those planes. Each returned tensor is therefore a
        *view* of `x` at `addr(x) + plane_index * H * W * T`, which
        `planner.py` resolves and `program.py` then encodes as an
        ordinary `in_addr` -- indistinguishable, to the hardware, from a
        tensor that was produced there in the first place.

        Every interior boundary (`sizes[0]`, `sizes[0]+sizes[1]`, ...)
        must be a multiple of `T = 8`; only the *last* part may have a
        channel count that is not, because only its trailing lanes
        coincide with `x`'s own zero-padded lanes rather than with
        another part's real data.

        YOLOv8n's C2f splits a multiple-of-16 channel count in half, so
        every boundary it needs is a multiple of 8.
        """
        if not sizes:
            raise ValueError(f"split of '{x.name}': `sizes` must not be empty")
        for index, size in enumerate(sizes):
            if size <= 0:
                raise ValueError(
                    f"split of '{x.name}': every part must have at least one channel, "
                    f"but sizes[{index}] = {size}"
                )
        if sum(sizes) != x.channels:
            raise ValueError(
                f"split of '{x.name}': sizes {list(sizes)} sum to {sum(sizes)}, but "
                f"'{x.name}' has {x.channels} channels -- a split must cover the tensor exactly"
            )
        if names is not None and len(names) != len(sizes):
            raise ValueError(
                f"split of '{x.name}': {len(names)} names given for {len(sizes)} parts"
            )

        boundary = 0
        parts: list[Tensor] = []
        for index, size in enumerate(sizes):
            if boundary % PLANE_CHANNELS != 0:
                raise ValueError(
                    f"split of '{x.name}': part {index} starts at channel {boundary}, which is "
                    f"not a multiple of the {PLANE_CHANNELS}-channel activation plane. "
                    f"A split is only free at a plane boundary; sizes {list(sizes)} would need "
                    f"a channel shuffle. Round the preceding part(s) to a multiple of "
                    f"{PLANE_CHANNELS}, or split into plane-aligned pieces and recombine them."
                )
            part = Tensor(
                name=(names[index] if names is not None else self._auto_name("split")),
                height=x.height,
                width=x.width,
                channels=size,
                quant=x.quant,
                alias_parent=x,
                alias_plane_offset=boundary // PLANE_CHANNELS,
                alias_role="slice",
            )
            self.tensors.append(part)
            parts.append(part)
            boundary += size
        return parts

    def concat(self, tensors: list[Tensor], *, name: str | None = None) -> Tensor:
        """Concatenate `tensors` along channels -- **free** whenever the
        planner can place each operand's producer output directly into
        the right slice of one buffer.

        Same layout argument as `split`: the result's plane list is
        operand 0's planes followed by operand 1's, and so on, so if each
        producer is simply told to write at `addr(result) + plane_offset
        * H * W * T` the concatenation has already happened by the time
        the last producer retires. No opcode, no instruction, and no
        extra DDR traffic.

        Two things stop an operand being placed that way, and both fall
        back to an explicit `COPY` (`model.copy`) into the slice:

        * it already lives inside some *other* buffer (it is a `split`
          view, or an operand of an earlier `concat`) -- a tensor cannot
          be in two places at once;
        * it is a graph input or a graph output, whose address is fixed
          by the DDR region layout rather than chosen by the planner.

        The one exception is the round trip `concat(split(t))`: when the
        operands are already contiguous, in order, inside one common
        parent, the result is returned as a plain view of that parent and
        still costs nothing.

        Every operand but the last must have a channel count that is a
        multiple of `T = 8`, for the same reason `split`'s interior
        boundaries must be: a non-plane-aligned operand's producer would
        zero the padding lanes it shares with the next operand's data.
        """
        if len(tensors) < 2:
            raise ValueError(
                f"concat needs at least two tensors, got {len(tensors)} -- "
                "concatenating one tensor is a no-op, say nothing instead"
            )
        first = tensors[0]
        for other in tensors[1:]:
            if (other.height, other.width) != (first.height, first.width):
                raise ValueError(
                    f"concat: spatial shape mismatch -- '{first.name}' is "
                    f"{first.height}x{first.width} (HxW) but '{other.name}' is "
                    f"{other.height}x{other.width}. Channel concatenation requires every "
                    "operand to have identical height and width."
                )
        for index, t in enumerate(tensors[:-1]):
            if t.channels % PLANE_CHANNELS != 0:
                raise ValueError(
                    f"concat: operand {index} '{t.name}' has {t.channels} channels, which is "
                    f"not a multiple of the {PLANE_CHANNELS}-channel activation plane. "
                    f"Only the LAST operand may be unaligned, because every other operand's "
                    f"padding lanes would overlap the next operand's real channels. "
                    f"Pad '{t.name}' to {(-(-t.channels // PLANE_CHANNELS)) * PLANE_CHANNELS} "
                    "channels, or reorder the concatenation so the unaligned operand is last."
                )

        total_channels = sum(t.channels for t in tensors)
        out_name = name or self._auto_name("concat")

        reviewed = self._concat_as_review(tensors, out_name, total_channels)
        if reviewed is not None:
            self.tensors.append(reviewed)
            return reviewed

        out_t = Tensor(
            name=out_name,
            height=first.height,
            width=first.width,
            channels=total_channels,
            quant=first.quant,
        )
        self.tensors.append(out_t)

        plane = 0
        for t in tensors:
            operand = t if self._can_be_concat_part(t) else self.copy(t, name=f"{out_name}_copy{plane}")
            operand.alias_parent = out_t
            operand.alias_plane_offset = plane
            operand.alias_role = "part"
            out_t.alias_parts.append(operand)
            plane += golden.activation_plane_count(t.channels)
        return out_t

    @staticmethod
    def _can_be_concat_part(t: Tensor) -> bool:
        """Can `t`'s bytes simply *be* the concat result's slice?

        Only if nothing else already dictates where those bytes live:
        `t` must own its buffer (`alias_parent is None`), must be
        produced by something whose output address the planner is free to
        choose (an op, or -- for a nested concat -- its own parts), and
        must not be pinned to a DDR region by being a graph input or a
        graph output."""
        if t.alias_parent is not None:
            return False
        if t.is_input or t.is_output:
            return False
        return t.producer is not None or bool(t.alias_parts)

    @staticmethod
    def _concat_as_review(tensors: list[Tensor], out_name: str, total_channels: int) -> Tensor | None:
        """`concat(split(p))` and friends: if every operand is already a
        view of one common parent and they sit contiguously, in order,
        the concatenation is that byte range and needs no buffer of its
        own. Returns the view tensor, or `None` when the general path
        applies."""
        first = tensors[0]
        if first.alias_parent is None:
            return None
        root = alias_root(first)
        start = alias_plane_offset_total(first)
        expected = start
        for t in tensors:
            if t.alias_parent is None or alias_root(t) is not root:
                return None
            if alias_plane_offset_total(t) != expected:
                return None
            expected += golden.activation_plane_count(t.channels)
        if expected * PLANE_CHANNELS > root.plane_count * PLANE_CHANNELS:
            return None
        return Tensor(
            name=out_name,
            height=first.height,
            width=first.width,
            channels=total_channels,
            quant=first.quant,
            alias_parent=root,
            alias_plane_offset=start,
            alias_role="slice",
        )

    # -- spatial tiling helpers (see `tiler.py`) ---------------------------

    def register_prebuilt_op(self, op: Op) -> Op:
        """Attach an `Op` this module did not build, wiring up the same
        `consumers`/`tensors` bookkeeping every builder method does.

        `tiler.py` constructs its clones directly rather than calling
        `conv2d`/`pool_max`/..., for one reason: those methods draw
        weights, biases and scale tables from the model's RNG, and a
        strip clone must reuse the *original* op's constants byte for
        byte or the tiled program computes a different (if equally valid)
        network and the tiled-vs-untiled oracle has nothing to compare.
        Op construction is a dataclass call; only the graph bookkeeping
        is worth sharing, and this is it."""
        self._register_op(op)
        return op

    def copy_rows(
        self,
        src: Tensor,
        rows: RowRange,
        *,
        into: Tensor | None = None,
        at: RowRange | None = None,
        name: str | None = None,
    ) -> Tensor:
        """Move rows `rows` of `src` into `into`'s rows `at` (or into a
        fresh compact tensor of `rows.rows` rows when `into` is `None`).

        The two forms are the two halves of tiling. `into=None` *extracts*
        a window -- the group-input LOAD of a strip, and the row
        alignment a join needs when one operand's strip is taller than
        the join's output. `into=<tensor>` *stores* a strip back into a
        full-resolution buffer at a row offset, which is how `S` strips
        assemble one group output.

        `at` defaults to `rows` (same rows at both ends), which is what
        the store form of a strip whose destination shares the source's
        coordinate system wants; the extract form always lands at row 0
        of its fresh buffer.

        No opcode is chosen here: `planner.py` resolves the two operand
        spaces and `program.py` picks `LOAD`/`STORE`/`COPY` from them,
        the same way it already does for a spill or a reload."""
        if rows.rows <= 0:
            raise ValueError(
                f"copy_rows of '{src.name}': {rows} is empty -- a row copy must move at "
                "least one row (an empty strip is a tiler bug, not a legal program)"
            )
        if rows.r0 < 0 or rows.r1 > src.height:
            raise ValueError(
                f"copy_rows of '{src.name}': {rows} is outside the tensor's "
                f"{src.height} rows"
            )

        if into is None:
            dst = Tensor(
                name=name or self._auto_name("rowcopy"),
                height=rows.rows,
                width=src.width,
                channels=src.channels,
                quant=src.quant,
            )
            dst_rows = RowRange(0, rows.rows)
        else:
            dst = into
            dst_rows = at if at is not None else rows
            if dst_rows.rows != rows.rows:
                raise ValueError(
                    f"copy_rows into '{into.name}': source {rows} is {rows.rows} rows but "
                    f"destination {dst_rows} is {dst_rows.rows} -- a row copy moves rows, "
                    "it does not resample them"
                )
            if dst_rows.r0 < 0 or dst_rows.r1 > into.height:
                raise ValueError(
                    f"copy_rows into '{into.name}': {dst_rows} is outside the tensor's "
                    f"{into.height} rows"
                )

        if src.width != dst.width or src.plane_count != dst.plane_count:
            raise ValueError(
                f"copy_rows '{src.name}' -> '{dst.name}': the two ends must agree on width "
                f"and plane count (got {src.width}x{src.plane_count} planes vs "
                f"{dst.width}x{dst.plane_count}). A row copy moves whole plane-rows; it "
                "never reshapes channels and never splits a plane."
            )

        op = RowCopyOp(name=dst.name, inputs=[src], output=dst, src_rows=rows, dst_rows=dst_rows)
        if into is None:
            # Only the extract form owns its output. A store form's
            # destination has several writers (one per strip) and
            # therefore no single `producer` -- `planner.py` counts
            # writers by walking `Model.ops`, exactly so this works.
            dst.producer = op
        self._register_op(op)
        return dst

    def add_planewise(
        self,
        a: Tensor,
        b: Tensor,
        *,
        requant_scale: int | None = None,
        requant_shift: int | None = None,
        output_scale: float | None = None,
        name: str | None = None,
    ) -> Tensor:
        """`add(a, b)`, but emitted as one `ADD` **per activation plane**
        and re-concatenated -- arithmetically identical, and the only
        form a tiled program may use.

        `cnn_accel_elementwise.vhd` issues an `ADD` as a single request
        per operand covering the whole tensor (`in_w*in_h*T*8` bytes),
        while `cnn_accel_tensor_mem` serves any one request from the
        single bank its address decodes to. A multi-plane strip buffer is
        deliberately allowed to span banks at plane granularity
        (`Tensor.confine_unit_bytes`), so a whole-tensor `ADD` request
        over one would be silently clamped. Splitting the add along
        planes -- which is free, `split`/`concat` are pure aliasing --
        keeps every request inside one plane and therefore inside one
        bank.

        Degenerates to a plain `add` for a single-plane tensor, so the
        untiled catalogue is unaffected."""
        if (a.height, a.width, a.channels) != (b.height, b.width, b.channels):
            raise ValueError(
                f"add_planewise: shape mismatch {a.height, a.width, a.channels} vs "
                f"{b.height, b.width, b.channels}"
            )
        out_name = name or self._auto_name("add")
        if a.plane_count == 1:
            return self.add(
                a,
                b,
                requant_scale=requant_scale,
                requant_shift=requant_shift,
                output_scale=output_scale,
                name=out_name,
            )

        sizes = _plane_sizes(a.channels)
        a_planes = self.split(a, sizes, names=[f"{out_name}_a{i}" for i in range(len(sizes))])
        b_planes = self.split(b, sizes, names=[f"{out_name}_b{i}" for i in range(len(sizes))])
        sums = [
            self.add(
                ap,
                bp,
                requant_scale=requant_scale,
                requant_shift=requant_shift,
                output_scale=output_scale,
                name=f"{out_name}_p{i}",
            )
            for i, (ap, bp) in enumerate(zip(a_planes, b_planes))
        ]
        return self.concat(sums, name=out_name)

    def act(self, x: Tensor, lut: list[int] | None = None, *, name: str | None = None) -> Tensor:
        """`OPCODE_ACT`. `lut[raw_byte] -> int8` for `raw_byte` in
        `0..255` (i.e. indexed by the *unsigned* byte representation of
        the signed input, matching a hardware LUT addressed by the raw
        activation byte); defaults to a ReLU LUT if omitted."""
        if lut is None:
            lut = [max(0, b - 256 if b >= 128 else b) for b in range(256)]
        if len(lut) != 256:
            raise ValueError(f"act: lut must have exactly 256 entries, got {len(lut)}")
        out_t = Tensor(
            name=name or self._auto_name("act"), height=x.height, width=x.width, channels=x.channels, quant=x.quant
        )
        op = ActOp(name=out_t.name, inputs=[x], output=out_t, lut=list(lut))
        out_t.producer = op
        self._register_op(op)
        return out_t


def _plane_sizes(channels: int) -> list[int]:
    """`channels` cut into one entry per activation plane: `T` channels
    each, with a short last entry when `channels` is not a multiple of
    `T`. The channel counts a `split` needs to name every plane of a
    tensor individually (`Model.add_planewise`)."""
    sizes = [PLANE_CHANNELS] * (channels // PLANE_CHANNELS)
    if channels % PLANE_CHANNELS:
        sizes.append(channels % PLANE_CHANNELS)
    return sizes


class _Rng:
    """Thin wrapper around `random.Random(seed)` so every random draw
    used by `Model` funnels through one place, named by what it is
    generating (keeps `Model`'s builder methods free of magic-number
    ranges)."""

    def __init__(self, seed: int) -> None:
        import random

        self._r = random.Random(seed)

    def int8_list(self, n: int, low: int = -128, high: int = 127) -> list[int]:
        return [self._r.randint(low, high) for _ in range(n)]

    def bias_list(self, n: int, magnitude: int = 2000) -> list[int]:
        return [self._r.randint(-magnitude, magnitude) for _ in range(n)]

    def scale_table(self, n: int) -> list[tuple[int, int]]:
        return [quantize_scale(self._r.uniform(1e-3, 2.0)) for _ in range(n)]


