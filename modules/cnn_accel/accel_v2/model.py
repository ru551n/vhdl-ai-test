"""Hand-written network builder -- deliberately **not** TOSA/MLIR-based.

This is the object-oriented "model-building framework" a test author uses
to construct a small tensor program directly in Python: tensors carry a
shape and a quantization scale, and operations (`conv2d`, `add`,
`upsample2x`, `pool_max`/`pool_avg`, `copy`, `act`) are chained purely by
dataflow (an op's inputs are the `Tensor` objects returned by earlier
calls). `planner.py` turns the resulting graph into a residency-aware
program; `reference.py` executes it bit-exactly; `program.py` lowers it to
`DescV2`s and a `MemoryImage`.

Authoritative source for op semantics: `doc/cnn_accel_top_v2_arch.md`
section 5 (opcode table, W0 flags). The actual arithmetic is never
reimplemented here -- every numeric op is a thin wrapper that
`reference.py` later drives through `cnn_accel_model.py`'s existing
`conv2d`/`pool_max`/`pool_avg`/`bias_requantize_relu`. This module only
knows shapes, random data and which HW fields an op needs.

Weights/biases/inputs/per-channel scale tables are generated by a single
`random.Random(seed)` instance owned by the `Model`, consumed in
call order, so two `Model` runs built with the same seed (and the same
sequence of builder calls) produce byte-identical data -- the
determinism the spec's test list asks for.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from enum import Enum, auto
from itertools import count

import cnn_accel_model as golden

# ---------------------------------------------------------------------------
# Compiler-side helper: real scale -> (requant_scale, requant_shift).
#
# This has NO counterpart in cnn_accel_model.py: that module only knows how
# to *apply* a already-chosen (multiplier, shift) pair
# (`bias_requantize_relu`/`round_shift_right_signed`), which is the
# hardware-bit-exact half and is reused verbatim. Computing suitable
# fixed-point parameters from a floating-point ratio is a compiler
# concern with no hardware behaviour to be bit-exact against, so it is
# implemented here, once, rather than approximated ad hoc in every test.
# ---------------------------------------------------------------------------


def quantize_scale(real_scale: float, *, max_shift: int = 200) -> tuple[int, int]:
    """Choose a signed Q15 `requant_scale` (W9) and `requant_shift` (W10,
    `0..max_shift`) such that

        requant_scale / 2**(15 + requant_shift) ~= real_scale

    using as many mantissa bits as the 32-bit signed `requant_scale`
    field allows (`frexp`-normalize `real_scale` into `[0.5, 1)` times a
    power of two, then keep 32 bits of that mantissa), the same idea as
    TFLite's `QuantizeMultiplier` adapted to this ISA's Q15-plus-extra-
    shift encoding instead of a plain Q31 multiplier. Only used by
    `Model`'s builder methods to turn a friendly `output_scale`/
    `weight_scale` ratio into descriptor fields; never consulted by
    `reference.py`, which only ever *applies* the resulting
    `(requant_scale, requant_shift)` via `cnn_accel_model.
    bias_requantize_relu` (reused, not reimplemented)."""
    if real_scale <= 0:
        raise ValueError(f"real_scale must be positive, got {real_scale}")

    mantissa, exponent = math.frexp(real_scale)  # real_scale == mantissa * 2**exponent, 0.5 <= mantissa < 1
    shift = 16 - exponent
    if shift < 0:
        shift = 0
    if shift > max_shift:
        shift = max_shift

    multiplier = round(real_scale * (2 ** (15 + shift)))
    # Rounding at the mantissa's 0.5 boundary (or a large max_shift clamp)
    # can push the multiplier to/past 2**31; renormalize downward rather
    # than encode a value that would not round-trip through the signed
    # 32-bit `requant_scale` field.
    while multiplier >= 2**31 and shift > 0:
        multiplier = round(multiplier / 2)
        shift -= 1
    multiplier = min(multiplier, 2**31 - 1)
    return multiplier, shift


