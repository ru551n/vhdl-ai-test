@dataclass(frozen=True)
class QuantParams:
    """Per-tensor symmetric int8 quantization: `real_value = int8_value *
    scale`. No zero-point: nowhere in the HW epilogue
    (`cnn_accel_model.bias_requantize_relu`) is a per-element zero-point
    subtracted -- the only additive term is the integer `output_offset`
    applied once, after the shift, to the whole lane. A caller targeting
    an asymmetric TOSA tensor must fold its zero-point into
    `output_offset` itself; `QuantParams` intentionally has no field that
    would suggest otherwise."""

    scale: float

    def __post_init__(self) -> None:
        if self.scale <= 0:
            raise ValueError(f"quant scale must be positive, got {self.scale}")


@dataclass(frozen=True)
class RowRange:
    """A half-open range of rows `[r0, r1)` in ONE tensor's own row
    coordinate system.

    Spatial tiling (`tiler.py`) is entirely a statement about row ranges:
    which rows of which full-resolution tensor a compact strip buffer
    holds, and which rows of an input a strip's output rows were computed
    from. Frozen (and therefore hashable) because a `RowRange` is a value,
    never a mutable cursor -- the tiler unions and translates them and
    must never alias one by accident."""

    r0: int  # inclusive
    r1: int  # exclusive

    def __post_init__(self) -> None:
        if self.r1 < self.r0:
            raise ValueError(f"RowRange: r1={self.r1} is below r0={self.r0}")

    @property
    def rows(self) -> int:
        return self.r1 - self.r0

    def clip(self, height: int) -> "RowRange":
        """This range intersected with `[0, height)` -- the receptive-field
        recurrence routinely produces a range that runs off the top or
        bottom of a tensor (that is exactly what padding is), and the
        strip buffer only ever holds rows that really exist."""
        return RowRange(max(0, self.r0), min(height, self.r1))

    def hull(self, other: "RowRange") -> "RowRange":
        """Smallest range containing both. Used to union the requirements
        of several consumers of one tensor: two consumers may ask for
        ranges that do not touch, and materializing the hull costs a few
        recomputed rows but keeps every strip buffer one contiguous,
        compact tensor (the only thing `in_plane_bytes` can describe --
        see `tiler.py`'s module docstring, hardware fact F2)."""
        return RowRange(min(self.r0, other.r0), max(self.r1, other.r1))

    def shift(self, delta: int) -> "RowRange":
        return RowRange(self.r0 + delta, self.r1 + delta)


@dataclass(frozen=True)
class StripOrigin:
    """Provenance of a strip tensor: which full-resolution tensor it is a
    piece of, and which of that tensor's rows this compact buffer holds.

    Never consulted by `planner.py`, `program.py` or `reference.py` -- it
    exists so the tiler's own geometry assertions, the tests and a
    program dump can say *what a buffer is* without re-deriving it from
    the addresses. The project's standing blind spot is that the DUT and
    `reference.py` both take their addresses from the planner, so a
    placement bug is self-consistently wrong on both sides; an
    independent record of the intended geometry is what a test checks the
    plan against."""

    full: "Tensor"
    rows: RowRange
    strip: int


@dataclass
class Tensor:
    """One node in the dataflow graph. `height/width/channels` is the
    LOGICAL HWC shape `cnn_accel_model.conv2d`/`pool_*` operate on --
    never the DDR channel-tiled-plane layout, which is a `reference.py`/
    `program.py` concern applied only at the memory boundary."""

    name: str
    height: int
    width: int
    channels: int
    quant: QuantParams
    producer: "Op | None" = None
    is_input: bool = False
    is_output: bool = False
    #: LOGICAL HWC int8 values, `-128..127`. Populated eagerly (from the
    #: model's RNG) for `is_input` tensors; populated for every other
    #: tensor only after `reference.run_reference` executes its producer.
    data: list[int] | None = None
    #: Indices into `Model.ops`, in the chronological order this tensor
    #: was consumed -- the liveness information `planner.py` needs and
    #: hardware deliberately does not track (section 3.1).
    consumers: list[int] = field(default_factory=list)

    # -- channel-plane aliasing (CONCAT / SPLIT, see `Model.concat`) -------
    #
    # The section-3 activation layout is channel-plane-major
    # (`byte_offset = ((c_tile * H + y) * W + x) * T + t`, `T = 8`), so a
    # tensor is exactly `ceil(C/T)` CONTIGUOUS planes of `H*W*T` bytes.
    # Concatenating along channels is therefore nothing but placing the
    # operands' planes back to back inside one buffer, and splitting
    # along a multiple-of-`T` channel boundary is nothing but naming a
    # sub-range of a parent's planes. Both are expressed here as an
    # *alias edge* to a parent tensor and cost no opcode, no instruction
    # and no byte of data movement.

    #: The tensor whose buffer this one lives inside, or `None` when this
    #: tensor owns its own allocation (it is an alias "root").
    alias_parent: "Tensor | None" = None
    #: This tensor's first plane, counted in `T`-channel planes from
    #: `alias_parent`'s first plane. Meaningless when `alias_parent` is
    #: `None`.
    alias_plane_offset: int = 0
    #: Which direction the alias edge carries data:
    #:
    #: * ``"part"``  -- this tensor's *producer writes into* the parent's
    #:   buffer; the parent (a CONCAT result) has no producer of its own
    #:   and its contents are the union of its parts.
    #: * ``"slice"`` -- this tensor is a read-only view *derived from* the
    #:   parent's contents (a SPLIT output, or a CONCAT that turned out to
    #:   be a contiguous re-view of one existing tensor).
    alias_role: str | None = None
    #: The tensors aliased into this one with `alias_role == "part"`, in
    #: ascending `alias_plane_offset` order. Non-empty exactly for a
    #: CONCAT result that owns a buffer.
    alias_parts: list["Tensor"] = field(default_factory=list)

    # -- spatial tiling (see `tiler.py`) ------------------------------------

    #: Set by `tiler.py` on a strip buffer: which rows of which
    #: full-resolution tensor these bytes are. `None` for every tensor of
    #: an untiled graph.
    origin: "StripOrigin | None" = None
    #: Keep this tensor in DDR for its whole lifetime, unconditionally.
    #:
    #: A full-resolution tensor on a fusion-group boundary is written by
    #: `S` separate strip `RowCopyOp`s and read by the next group's, so it
    #: has no single producer, several writers, and a lifetime spanning
    #: groups -- it is backing storage by design, not a scratchpad
    #: resident. `planner.py` takes its existing `place_in_ddr` path for
    #: such a tensor immediately and unconditionally, and reports the
    #: bytes separately (`DdrTraffic.pinned_*_bytes`) from the bytes an
    #: overflow *fallback* cost, so a test can still assert "this program
    #: paid nothing for overflow" while the group boundaries cost exactly
    #: what the tiling says they should.
    pin_ddr: bool = False
    #: The granularity at which this tensor's buffer must stay inside one
    #: `cnn_accel_tensor_mem` bank (see `planner._LocalAllocator`), or
    #: `None` for "the whole buffer" -- which is what every untiled
    #: tensor wants and what this planner has always enforced.
    #:
    #: The hardware requirement is not "a buffer lies in one bank" but
    #: "no single *request* straddles a bank": `cnn_accel_tensor_mem`
    #: serves each request from the bank its address decodes to and
    #: silently clamps the overrun. For a strip activation buffer every
    #: request is at most one channel plane (`cmd_proc.vhd`'s ifmap
    #: feeder fetches one `(row, tile)` strip per request, output passes
    #: write one plane), so confining *planes* rather than the whole
    #: buffer is what lets a multi-plane strip be larger than a bank at
    #: all. Left `None` everywhere outside `tiler.py`, so no existing
    #: placement moves.
    confine_unit_bytes: int | None = None

    @property
    def size_bytes(self) -> int:
        """DDR/LOCAL_TENSOR byte footprint of this tensor in the
        section-3 channel-tiled-plane layout (identical in both spaces)."""
        return golden.activation_bytes(self.width, self.height, self.channels)

    @property
    def plane_bytes(self) -> int:
        """Bytes in one `T`-channel activation plane of this tensor."""
        return PLANE_CHANNELS * self.width * self.height

    @property
    def plane_count(self) -> int:
        return golden.activation_plane_count(self.channels)

    @property
    def row_bytes(self) -> int:
        """Bytes in one row of ONE `T`-channel activation plane. The unit
        a `RowCopyOp` moves: `plane_bytes` is `height * row_bytes`, and
        row `y` of plane `p` starts at `p * plane_bytes + y * row_bytes`."""
        return PLANE_CHANNELS * self.width


PLANE_CHANNELS = golden.ACTIVATION_PLANE_CHANNELS


def alias_root(tensor: Tensor) -> Tensor:
    """The tensor that actually owns the buffer `tensor` lives in --
    `tensor` itself when it is not aliased. Alias edges always point
    "outward" to a larger buffer and can nest (a CONCAT of a CONCAT
    result), so this walks the chain to its end."""
    node = tensor
    seen = 0
    while node.alias_parent is not None:
        node = node.alias_parent
        seen += 1
        if seen > 64:  # pragma: no cover - would mean a builder bug
            raise ValueError(f"alias chain from '{tensor.name}' does not terminate")
    return node


def alias_plane_offset_total(tensor: Tensor) -> int:
    """`tensor`'s first plane, counted from `alias_root(tensor)`'s first
    plane."""
    total = 0
    node = tensor
    while node.alias_parent is not None:
        total += node.alias_plane_offset
        node = node.alias_parent
    return total


def alias_byte_offset(tensor: Tensor) -> int:
    """Byte offset of `tensor` inside `alias_root(tensor)`'s buffer.

    Every alias edge preserves `height`/`width` (both `concat` and
    `split` require it), so one plane is the same number of bytes
    everywhere along the chain."""
    return alias_plane_offset_total(tensor) * tensor.plane_bytes


class Activation(Enum):
    """Epilogue activation choice for a compute op, orthogonal to
    `clamp` (section 5.1: `CLAMP_EN` set means `clamp_min`/`clamp_max`
    are used and `RELU_EN` is ignored; `CLAMP_EN` clear falls back to the
    legacy `RELU_EN`-selected `[0 or -128, 127]` range -- see
    `cnn_accel_model.bias_requantize_relu`)."""

    NONE = auto()
    RELU = auto()


# ---------------------------------------------------------------------------
# Ops. Each carries everything `reference.py`/`program.py` need: shapes
# live on the `Tensor`s, so an `Op` only carries the extra per-instruction
# parameters (kernel/stride/pad, weights, requant, ...).
# ---------------------------------------------------------------------------


@dataclass
class Op:
    name: str
    inputs: list[Tensor]
    output: Tensor


@dataclass
class Conv2dOp(Op):
    """`OPCODE_CONV2D`. `weight` is LOGICAL OHWI (module docstring of
    `cnn_accel_model.py`); `bias` is one int32 per output channel or
    `None` (`BIAS_EN` clear)."""

    weight: list[int]
    bias: list[int] | None
    kernel: tuple[int, int]
    stride: tuple[int, int]
    padding: tuple[int, int, int, int]  # (top, bottom, left, right)
    activation: Activation
    clamp: tuple[int, int] | None
    requant_scale: int
    requant_shift: int
    output_offset: int = 0
    per_channel_scale: list[tuple[int, int]] | None = None
    #: ISA v2.1 `pad_value`: the int8 value a padded tap takes -- the
    #: input tensor's quantization zero-point, NOT 0. Declared here rather
    #: than next to `padding` only because every field between them lacks
    #: a default and a dataclass cannot put a defaulted field first.
    #: Padding a quantized tensor with 0 adds `sum(w) * (0 - zp)` to every
    #: border accumulator; with YOLOv8n's 3x3/pad-1 convolutions that is
    #: every border output of every layer. 0 keeps pre-v2.1 behaviour.
    pad_value: int = 0
    #: ISA v2.0 `WEIGHT_REUSE` (R6): when set, this op's weight/bias/
    #: scale buffers are already resident from `reused_weight_op` and
    #: must not be refetched -- `planner.py` charges it zero weight
    #: bytes, `program.py` points its weight/bias/scale addresses at
    #: `reused_weight_op`'s own allocation instead of making a new one.
    weight_reuse: bool = False
    reused_weight_op: "Conv2dOp | None" = None
    #: Serve this op's packed weight/bias/scale images out of the
    #: scratchpad (`space_wgt = LOCAL_TENSOR`) instead of DDR.
    #:
    #: The hardware refills the weight buffer once per output-channel
    #: pass either way (`cmd_proc.vhd`'s `st_wgt_req`, which is skipped
    #: only by `WEIGHT_REUSE` and by `LOCAL_WEIGHT`); what this flag
    #: changes is where those `n_ot` fetches come *from*. For a tiled
    #: group that is the difference between reading the group's weights
    #: from DDR once per strip and reading them once in total: with `S`
    #: strips the DDR weight traffic goes from `S * W_G` to `W_G`, which
    #: on YOLOv8n at 256 KiB is several megabytes a frame.
    #:
    #: `planner.py` gives the images a local home (all convolutions
    #: sharing one `weight` list share one image), emits the `LOAD` as a
    #: `ConstLoadStep`, and silently falls back to DDR for the whole
    #: image if it cannot be placed -- so the flag is a request, never a
    #: promise, and a plan that ignores it is still correct.
    #:
    #: This is NOT `weight_reuse`: that flag skips the refill outright
    #: and is only correct for `out_channels <= PE_ROWS` (R8). The two
    #: are independent, and the tiler sets only this one.
    weights_resident: bool = False

    def flags(self) -> int:
        """W0 `flags` byte (section 5.1) for this op's `CONV2D`
        descriptor. The single place this is computed -- `reference.py`
        and `program.py` both call this rather than each re-deriving the
        same bits from `activation`/`clamp`/`bias`/`padding`/
        `per_channel_scale`/`weight_reuse`, so the executor and the
        descriptor emitter cannot silently disagree about which
        epilogue stages are enabled."""
        f = 0
        if self.bias is not None:
            f |= 1 << golden.FLAG_BIAS_EN
        f |= 1 << golden.FLAG_REQUANT_EN
        if self.clamp is not None:
            f |= 1 << golden.FLAG_CLAMP_EN
        elif self.activation == Activation.RELU:
            f |= 1 << golden.FLAG_RELU_EN
        if self.per_channel_scale is not None:
            f |= 1 << golden.FLAG_PER_CHANNEL_EN
        if any(self.padding):
            f |= 1 << golden.FLAG_PAD_EN
        if self.weight_reuse:
            f |= 1 << golden.FLAG_WEIGHT_REUSE
        return f

    def weight_layer_desc(self) -> golden.LayerDesc:
        """A minimal `cnn_accel_model.LayerDesc` carrying only the fields
        `pack_weights_for_hw`/`packed_weight_count`/`pack_bias_for_hw`/
        `pack_scale_table_for_hw` actually read (`in_channels`,
        `out_channels`, `kernel_h`, `kernel_w`). The single place both
        `planner.py` (byte-count prediction) and `program.py` (actual
        packing) build this from, so the two can never drift apart."""
        x = self.inputs[0]
        return golden.LayerDesc(
            opcode=golden.OPCODE_CONV2D,
            in_channels=x.channels,
            out_channels=self.output.channels,
            kernel_h=self.kernel[0],
            kernel_w=self.kernel[1],
        )


@dataclass
class PoolOp(Op):
    """`OPCODE_POOL_MAX`/`OPCODE_POOL_AVG`.

    ISA v2.1: pooling now has padding, reusing `CONV2D`'s own
    `FLAG_PAD_EN` + `pad_top/bottom/left/right` fields, plus `pad_value`
    -- the int8 value padded taps take, which for a real quantized tensor
    is its zero-point and NOT 0 (see `cnn_accel_model._pool_windows`).
    YOLOv8n's SPPF block is the motivating shape: 5x5 max pool, stride 1,
    padding 2, on a tensor with zero_point = -128."""

    mode: str  # "max" | "avg"
    kernel: tuple[int, int]
    stride: tuple[int, int]
    padding: tuple[int, int, int, int] = (0, 0, 0, 0)  # (top, bottom, left, right)
    pad_value: int = 0
    activation: Activation = Activation.NONE
    clamp: tuple[int, int] | None = None
    requant_scale: int = 0
    requant_shift: int = 0
    output_offset: int = 0

    def flags(self) -> int:
        """W0 `flags` byte for this op's `POOL_MAX`/`POOL_AVG`
        descriptor -- see `Conv2dOp.flags` for why this is centralized
        here rather than re-derived by each caller. `POOL_AVG` always
        sets `REQUANT_EN` (division is implemented as the epilogue's
        requantize step, section 5.2); `POOL_MAX` never does (integer
        max has no scale to correct)."""
        f = 0
        if self.mode == "avg":
            f |= 1 << golden.FLAG_REQUANT_EN
        if self.clamp is not None:
            f |= 1 << golden.FLAG_CLAMP_EN
        elif self.activation == Activation.RELU:
            f |= 1 << golden.FLAG_RELU_EN
        if any(self.padding):
            f |= 1 << golden.FLAG_PAD_EN
        return f


